async function getPeriodSettings(
  tenantId,
  timezone
){

  let settings =
    await PayrollPeriodSettings
      .findOne({
        tenantId
      });

  if(settings){
    return settings;
  }

  /*
    Safe initial default:
    current Sunday -> Saturday.
    Super Admin can change it once from the Payroll page.
  */

  const today =
    serverTodayKey(
      timezone
    );

  const date =
    keyToUtc(today);

  const start =
    addDaysKey(
      today,
      -date.getUTCDay()
    );

  settings =
    await PayrollPeriodSettings
      .create({
        tenantId,
        anchorStart:start,
        periodLengthDays:7,
        archiveCursorStart:start
      });

  return settings;
}

function resolvePeriod(
  settings,
  dateKey
){

  const anchor =
    clean(
      settings.anchorStart
    );

  const length =
    Math.max(
      1,
      Number(
        settings.periodLengthDays ||
        7
      )
    );

  const dayOffset =
    diffDays(
      anchor,
      dateKey
    );

  const periodIndex =
    Math.floor(
      dayOffset /
      length
    );

  const start =
    addDaysKey(
      anchor,
      periodIndex * length
    );

  const end =
    addDaysKey(
      start,
      length - 1
    );

  return {
    start,
    end,
    lengthDays:length,
    periodIndex
  };
}

async function getCurrentPeriod(
  tenantId
){

  const timezone =
    await tenantTimezone(
      tenantId
    );

  const settings =
    await getPeriodSettings(
      tenantId,
      timezone
    );

  const today =
    serverTodayKey(
      timezone
    );

  return {
    timezone,
    today,
    settings,
    period:
      resolvePeriod(
        settings,
        today
      )
  };
}


/* =========================
   TRIP STATUS HELPERS
========================= */

function normalizeStatus(value){

  return clean(value)
    .toUpperCase()
    .replace(/[\s_-]+/g,"");
}

function tripStatus(trip){

  return (
    normalizeStatus(
      trip?.status
    ) ||
    normalizeStatus(
      trip?.dispatchStatus
    )
  );
}

function isCancelled(trip){

  const s =
    tripStatus(trip);

  return (
    s === "CANCELLED" ||
    s === "CANCELED"
  );
}

function isNotCompleted(trip){

  return (
    tripStatus(trip) ===
    "NOTCOMPLETED"
  );
}

function isCompleted(trip){

  return (
    tripStatus(trip) ===
    "COMPLETED"
  );
}

function isNoShow(trip){

  return (
    tripStatus(trip) ===
    "NOSHOW"
  );
}

function isActiveTrip(trip){

  return [
    "ONTRIP",
    "INPROGRESS",
    "ARRIVED",
    "ACCEPTED",
    "SENT",
    "ASSIGNED",
    "SCHEDULED",
    "CONFIRMED",
    "AUTOASSIGNED"
  ].includes(
    tripStatus(trip)
  );
}

function scheduledDate(trip){

  const d =
    clean(
      trip?.tripDate ||
      trip?.date
    );

  const t =
    clean(
      trip?.tripTime ||
      trip?.time ||
      "00:00"
    );

  if(!d){
    return null;
  }

  const date =
    new Date(
      `${d}T${t}`
    );

  return Number.isNaN(
    date.getTime()
  )
    ? null
    : date;
}

function finalMoment(trip){

  const candidates = [
    trip?.historyAt,
    trip?.finalizedAt,
    trip?.finalStatusConfirmedAt,
    trip?.sharedFinalConfirmedAt,
    trip?.dispatchFinalConfirmedAt,
    trip?.cancelDateTime,
    trip?.assignmentCompletedAt
  ];

  for(
    const value
    of candidates
  ){

    if(!value){
      continue;
    }

    const date =
      new Date(value);

    if(
      !Number.isNaN(
        date.getTime()
      )
    ){
      return date;
    }
  }

  return null;
}


/* =========================
   DRIVER HOURS ENGINE

   Same business rule:
   first scheduled pickup -> last final time.
   Time between trips counts.
========================= */

function buildDriverDay(
  dayTrips,
  dayKey,
  todayKey
){

  const now =
    new Date();

  const workable =
    dayTrips
      .map(
        trip=>({
          trip,
          scheduled:
            scheduledDate(
              trip
            )
        })
      )
      .filter(
        item=>
          item.scheduled &&
          !isCancelled(
            item.trip
          ) &&
          !isNotCompleted(
            item.trip
          )
      )
      .sort(
        (a,b)=>
          a.scheduled -
          b.scheduled
      );

  if(!workable.length){
    return null;
  }

  const start =
    new Date(
      workable[0]
        .scheduled
    );

  if(
    dayKey ===
      todayKey &&
    now < start
  ){
    return null;
  }

  const finalTimes =
    workable
      .map(
        item=>{

          if(
            isCompleted(
              item.trip
            ) ||
            isNoShow(
              item.trip
            )
          ){
            return finalMoment(
              item.trip
            );
          }

          return null;
        }
      )
      .filter(Boolean);

  const hasOpenWork =
    workable.some(
      item=>
        isActiveTrip(
          item.trip
        ) &&
        item.scheduled <=
          now
    );

  let end = null;
  let running = false;

  if(
    dayKey ===
      todayKey &&
    hasOpenWork
  ){

    end = now;
    running = true;

  }else if(
    finalTimes.length
  ){

    end =
      new Date(
        Math.max(
          ...finalTimes
            .map(
              date=>
                date.getTime()
            )
        )
      );
  }

  if(
    !end ||
    end < start
  ){
    return null;
  }

  return {
    date:dayKey,
    start,
    end,
    hours:
      hours(
        (
          end -
          start
        ) /
        3600000
      ),
    running
  };
}

async function driverDailyHours(
  tenantId,
  driverId,
  from,
  to,
  timezone
){

  const Trip =
    global.Trip;

  if(!Trip){

    throw new Error(
      "Trip model is not ready"
    );
  }

  /*
    Read assignment status too, just like the
    existing driver trip pipeline.
  */

  const assignments =
    await DispatchAssignment
      .find({
        driverId:
          String(
            driverId
          )
      })
      .select(
        "tripId driverId dispatchStatus sentAt acceptedAt startedAt completedAt"
      )
      .lean();

  const tripIds =
    assignments
      .map(
        row=>
          row.tripId
      )
      .filter(Boolean);

  if(!tripIds.length){
    return [];
  }

  const assignmentMap =
    new Map();

  assignments
    .forEach(
      row=>{

        assignmentMap.set(
          String(row.tripId),
          row
        );
      }
    );

  const trips =
    await Trip
      .find({
        _id:{
          $in:tripIds
        },

        tenantId,

        tripDate:{
          $gte:from,
          $lte:to
        },

        disabled:{
          $ne:true
        }
      })
      .select(
        "tripDate tripTime status historyAt finalizedAt finalStatusConfirmedAt sharedFinalConfirmedAt dispatchFinalConfirmedAt cancelDateTime"
      )
      .lean();

  const groups = {};

  trips.forEach(
    trip=>{

      const assignment =
        assignmentMap.get(
          String(
            trip._id
          )
        ) ||
        {};

      const merged = {
        ...trip,

        dispatchStatus:
          assignment.dispatchStatus ||
          "",

        assignmentCompletedAt:
          assignment.completedAt ||
          null
      };

      const key =
        clean(
          merged.tripDate
        );

      if(!key){
        return;
      }

      if(!groups[key]){
        groups[key] = [];
      }

      groups[key]
        .push(
          merged
        );
    }
  );

  const todayKey =
    serverTodayKey(
      timezone
    );

  return Object
    .keys(groups)
    .sort()
    .map(
      key=>
        buildDriverDay(
          groups[key],
          key,
          todayKey
        )
    )
    .filter(Boolean);
}

