router.put(
  "/period",
  requirePayrollAuth,
  requireSuperAdmin,
  async(req,res)=>{

    try{

      const from =
        clean(
          req.body?.from
        );

      const to =
        clean(
          req.body?.to
        );

      if(
        !validDateKey(from) ||
        !validDateKey(to) ||
        from > to
      ){

        return res
          .status(400)
          .json({
            message:
              "Invalid pay period"
          });
      }

      const lengthDays =
        inclusiveDays(
          from,
          to
        );

      if(
        lengthDays < 1 ||
        lengthDays > 366
      ){

        return res
          .status(400)
          .json({
            message:
              "Invalid pay period length"
          });
      }

      const settings =
        await PayrollPeriodSettings
          .findOneAndUpdate(
            {
              tenantId:
                req.authUser
                  .tenantId
            },
            {
              $set:{
                anchorStart:
                  from,

                periodLengthDays:
                  lengthDays,

                archiveCursorStart:
                  from,

                updatedBy:
                  req.authUser.id
              }
            },
            {
              upsert:true,
              new:true,
              setDefaultsOnInsert:true
            }
          );

      const timezone =
        await tenantTimezone(
          req.authUser
            .tenantId
        );

      const today =
        serverTodayKey(
          timezone
        );

      const period =
        resolvePeriod(
          settings,
          today
        );

      return res.json({
        success:true,
        timezone,
        serverToday:today,
        period:{
          from:period.start,
          to:period.end,
          lengthDays:
            period.lengthDays
        }
      });

    }catch(err){

      console.log(
        "PAYROLL PERIOD SAVE ERROR:",
        err
      );

      return res
        .status(500)
        .json({
          message:
            "Pay period save failed"
        });
    }
  }
);


