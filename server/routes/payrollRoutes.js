/* =========================
   AUTOMATIC HISTORY SNAPSHOT
========================= */

const PERSON_TYPES = [
  "driver",
  "dispatcher",
  "admin",
  "super_admin",
  "employee"
];

async function archiveOnePeriod(
  tenantId,
  from,
  to,
  timezone
){

  for(
    const personType
    of PERSON_TYPES
  ){

    const people =
      await loadPeople(
        tenantId,
        personType
      );

    for(
      const person
      of people
    ){

      const calc =
        await calculatePerson(
          tenantId,
          personType,
          person,
          from,
          to,
          timezone
        );

      await PayrollPeriodHistory
        .findOneAndUpdate(
          {
            tenantId,
            personType,
            personId:
              String(
                person._id
              ),
            periodStart:from,
            periodEnd:to
          },
          {
            $setOnInsert:{
              personName:
                calc.name,

              timezone,

              regularHours:
                calc.regularHours,

              overtimeHours:
                calc.overtimeHours,

              totalHours:
                calc.totalHours,

              hourlyRate:
                calc.hourlyRate,

              overtimeRate:
                calc.overtimeRate,

              overtimeAfterHours:
                calc.overtimeAfterHours,

              regularPay:
                calc.regularPay,

              overtimePay:
                calc.overtimePay,

              totalDue:
                calc.totalDue,

              dailyHours:
                calc.dailyHours,

              closedAt:
                new Date()
            }
          },
          {
            upsert:true,
            new:true,
            setDefaultsOnInsert:true
          }
        );
    }
  }
}

async function ensureClosedPeriods(
  tenantId
){

  const info =
    await getCurrentPeriod(
      tenantId
    );

  const {
    timezone,
    settings,
    period
  } = info;

  let cursor =
    clean(
      settings
        .archiveCursorStart
    ) ||
    clean(
      settings
        .anchorStart
    );

  /*
    If configuration was created in the future,
    there is nothing to archive yet.
  */
  if(
    !cursor ||
    cursor >=
      period.start
  ){

    if(
      cursor !==
      period.start
    ){

      settings.archiveCursorStart =
        period.start;

      await settings.save();
    }

    return info;
  }

  let guard = 0;

  while(
    cursor <
      period.start &&
    guard < 60
  ){

    const end =
      addDaysKey(
        cursor,
        Number(
          settings
            .periodLengthDays ||
          7
        ) - 1
      );

    if(
      end >=
      period.start
    ){
      break;
    }

    await archiveOnePeriod(
      tenantId,
      cursor,
      end,
      timezone
    );

    cursor =
      addDaysKey(
        end,
        1
      );

    guard += 1;
  }

  settings.archiveCursorStart =
    period.start;

  await settings.save();

  return info;
}


