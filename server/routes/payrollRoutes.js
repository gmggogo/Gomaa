function readBearerToken(req){

  const header =
    String(
      req.headers?.authorization ||
      ""
    ).trim();

  if(
    !header
      .toLowerCase()
      .startsWith("bearer ")
  ){
    return "";
  }

  return header
    .slice(7)
    .trim();
}

function normalizedRole(value){

  return String(value || "")
    .trim()
    .toUpperCase()
    .replace(/[\s-]+/g,"_");
}

function requirePayrollAuth(
  req,
  res,
  next
){

  const token =
    readBearerToken(req);

  if(!token){

    return res
      .status(401)
      .json({
        success:false,
        message:"Access Denied"
      });
  }

  try{

    const verified =
      jwt.verify(
        token,
        JWT_SECRET
      );

    req.authUser = {
      id:
        String(
          verified.id ||
          ""
        ),

      role:
        String(
          verified.role ||
          ""
        ),

      tenantId:
        String(
          verified.tenantId ||
          ""
        )
    };

    if(!req.authUser.tenantId){

      return res
        .status(403)
        .json({
          success:false,
          message:"Tenant Required"
        });
    }

    next();

  }catch(err){

    return res
      .status(401)
      .json({
        success:false,
        message:"Invalid Token"
      });
  }
}

function requireSuperAdmin(
  req,
  res,
  next
){

  if(
    normalizedRole(
      req.authUser?.role
    ) !== "SUPER_ADMIN"
  ){

    return res
      .status(403)
      .json({
        success:false,
        message:"Super Admin only"
      });
  }

  next();
}


/* =========================
   BASIC HELPERS
========================= */

function clean(value){
  return String(value ?? "").trim();
}

function money(value){
  return Number(
    Number(value || 0)
      .toFixed(2)
  );
}

function hours(value){
  return Number(
    Number(value || 0)
      .toFixed(4)
  );
}

function validDateKey(value){

  return /^\d{4}-\d{2}-\d{2}$/
    .test(
      clean(value)
    );
}

/*
  Calendar math intentionally uses UTC.
  These are DATE KEYS, not local timestamps.
  This prevents Render/server local timezone from shifting the day.
*/

function keyToUtc(value){

  if(!validDateKey(value)){
    return null;
  }

  const [
    y,
    m,
    d
  ] =
    value
      .split("-")
      .map(Number);

  return new Date(
    Date.UTC(
      y,
      m - 1,
      d
    )
  );
}

function utcToKey(date){

  return [
    date.getUTCFullYear(),
    String(
      date.getUTCMonth() + 1
    ).padStart(2,"0"),
    String(
      date.getUTCDate()
    ).padStart(2,"0")
  ].join("-");
}

function addDaysKey(
  key,
  days
){

  const date =
    keyToUtc(key);

  if(!date){
    return "";
  }

  date.setUTCDate(
    date.getUTCDate() +
    Number(days || 0)
  );

  return utcToKey(date);
}

function diffDays(
  from,
  to
){

  const a =
    keyToUtc(from);

  const b =
    keyToUtc(to);

  if(!a || !b){
    return 0;
  }

  return Math.round(
    (
      b.getTime() -
      a.getTime()
    ) /
    86400000
  );
}

function inclusiveDays(
  from,
  to
){

  return (
    diffDays(
      from,
      to
    ) + 1
  );
}


/* =========================
   TENANT GLOBAL TIME ENGINE

   Source:
   SystemDesign for THIS tenant.

   The real current instant is generated by the server:
   new Date()

   The tenant timezone decides the calendar date.
========================= */

async function tenantTimezone(
  tenantId
){

  const design =
    await SystemDesign
      .findOne({
        tenantId
      })
      .select(
        "timezone"
      )
      .lean();

  const timezone =
    clean(
      design?.timezone
    ) ||
    "America/Phoenix";

  /*
    Validate IANA timezone.
  */
  try{

    new Intl.DateTimeFormat(
      "en-US",
      {
        timeZone:timezone
      }
    ).format(
      new Date()
    );

    return timezone;

  }catch(err){

    return "America/Phoenix";
  }
}

function dateKeyInTimezone(
  date,
  timezone
){

  const parts =
    new Intl.DateTimeFormat(
      "en-US",
      {
        timeZone:timezone,
        year:"numeric",
        month:"2-digit",
        day:"2-digit"
      }
    )
    .formatToParts(date);

  const map = {};

  for(const part of parts){
    map[part.type] =
      part.value;
  }

  return (
    `${map.year}-` +
    `${map.month}-` +
    `${map.day}`
  );
}

function serverTodayKey(
  timezone
){

  /*
    IMPORTANT:
    This begins with the SERVER'S real current instant.
    Device time is never used.
  */
  return dateKeyInTimezone(
    new Date(),
    timezone
  );
}


