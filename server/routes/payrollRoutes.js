/* =========================
   PAY CALCULATION

   Overtime resets every Sunday.
========================= */

function weekStartKey(
  dateKey
){

  const date =
    keyToUtc(
      dateKey
    );

  if(!date){
    return "";
  }

  return addDaysKey(
    dateKey,
    -date.getUTCDay()
  );
}

function splitRegularAndOvertime(
  dailyRows,
  overtimeAfterHours
){

  const threshold =
    Math.max(
      0,
      Number(
        overtimeAfterHours ??
        40
      )
    );

  const weeks =
    new Map();

  dailyRows
    .forEach(
      row=>{

        const week =
          weekStartKey(
            row.date
          );

        if(
          !weeks.has(
            week
          )
        ){
          weeks.set(
            week,
            []
          );
        }

        weeks
          .get(week)
          .push(row);
      }
    );

  let regularHours = 0;
  let overtimeHours = 0;

  for(
    const rows
    of weeks.values()
  ){

    const weekHours =
      rows.reduce(
        (sum,row)=>
          sum +
          Number(
            row.hours ||
            0
          ),
        0
      );

    regularHours +=
      Math.min(
        weekHours,
        threshold
      );

    overtimeHours +=
      Math.max(
        0,
        weekHours -
        threshold
      );
  }

  return {
    regularHours:
      hours(
        regularHours
      ),

    overtimeHours:
      hours(
        overtimeHours
      ),

    totalHours:
      hours(
        regularHours +
        overtimeHours
      )
  };
}

