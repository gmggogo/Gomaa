router.get(
  "/history",
  requirePayrollAuth,
  async(req,res)=>{

    try{

      const role =
        normalizedRole(
          req.authUser.role
        );

      const filter = {
        tenantId:
          req.authUser
            .tenantId
      };

      if(
        role === "DRIVER"
      ){

        filter.personType =
          "driver";

        filter.personId =
          String(
            req.authUser.id
          );

      }else if(
        role === "SUPER_ADMIN"
      ){

        const type =
          clean(
            req.query.type
          );

        if(
          type &&
          PERSON_TYPES
            .includes(type)
        ){
          filter.personType =
            type;
        }

        const personId =
          clean(
            req.query.personId
          );

        if(personId){
          filter.personId =
            personId;
        }

      }else{

        return res
          .status(403)
          .json({
            message:
              "Access denied"
          });
      }

      await ensureClosedPeriods(
        req.authUser.tenantId
      );

      const rows =
        await PayrollPeriodHistory
          .find(filter)
          .sort({
            periodStart:-1,
            personName:1
          })
          .limit(500)
          .lean();

      return res.json({
        success:true,
        history:rows
      });

    }catch(err){

      console.log(
        "PAYROLL HISTORY ERROR:",
        err
      );

      return res
        .status(500)
        .json({
          message:
            "Payroll history load failed"
        });
    }
  }
);

